-- Additive migration. Existing operational and report records are preserved.
CREATE TABLE IF NOT EXISTS reporting_cities (
  city_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_name VARCHAR(120) NOT NULL,
  normalized_city_name VARCHAR(120) NOT NULL UNIQUE,
  province VARCHAR(100), latitude NUMERIC(10,6), longitude NUMERIC(10,6)
);
ALTER TABLE reporting_cities ADD COLUMN IF NOT EXISTS operational_city_id VARCHAR(16) REFERENCES cities(city_id);
CREATE INDEX IF NOT EXISTS reporting_cities_operational_idx ON reporting_cities(operational_city_id);

CREATE TABLE IF NOT EXISTS report_import_batches (
  batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_sha256 CHAR(64) NOT NULL UNIQUE,
  source_file_name TEXT NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reconciliation JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS report_source_rows (
  batch_id BIGINT NOT NULL REFERENCES report_import_batches(batch_id),
  source_sheet TEXT NOT NULL, source_row INTEGER NOT NULL,
  cached_values JSONB NOT NULL, formulas JSONB NOT NULL,
  PRIMARY KEY(batch_id, source_sheet, source_row)
);
CREATE TABLE IF NOT EXISTS report_import_backups (
  batch_id BIGINT PRIMARY KEY REFERENCES report_import_batches(batch_id),
  previous_rows JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS monthly_collection_reports (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id BIGINT REFERENCES reporting_cities(city_id), report_month DATE NOT NULL,
  collection_channel VARCHAR(20) NOT NULL, box_count INTEGER, amount_pkr NUMERIC(24,10),
  source_city_name VARCHAR(120), source_sheet VARCHAR(80) NOT NULL, source_row INTEGER NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(source_sheet, source_row)
);
CREATE TABLE IF NOT EXISTS monthly_expense_reports (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id BIGINT REFERENCES reporting_cities(city_id), report_month DATE NOT NULL,
  expense_category VARCHAR(80) NOT NULL, amount_pkr NUMERIC(24,10),
  source_city_name VARCHAR(120), source_sheet VARCHAR(80) NOT NULL, source_row INTEGER NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(source_sheet, source_row)
);
CREATE TABLE IF NOT EXISTS monthly_staff_counts (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id BIGINT REFERENCES reporting_cities(city_id), report_month DATE NOT NULL, staff_count INTEGER,
  source_city_name VARCHAR(120), source_sheet VARCHAR(80) NOT NULL, source_row INTEGER NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(source_sheet, source_row)
);
ALTER TABLE monthly_collection_reports ALTER COLUMN amount_pkr TYPE NUMERIC(24,10);
ALTER TABLE monthly_expense_reports ALTER COLUMN amount_pkr TYPE NUMERIC(24,10);
ALTER TABLE monthly_collection_reports ADD COLUMN IF NOT EXISTS target_pkr NUMERIC(24,10);
ALTER TABLE monthly_collection_reports ADD COLUMN IF NOT EXISTS source_value_state VARCHAR(16);
ALTER TABLE monthly_expense_reports ADD COLUMN IF NOT EXISTS source_value_state VARCHAR(16);
ALTER TABLE monthly_collection_reports ADD COLUMN IF NOT EXISTS import_batch_id BIGINT REFERENCES report_import_batches(batch_id);
ALTER TABLE monthly_expense_reports ADD COLUMN IF NOT EXISTS import_batch_id BIGINT REFERENCES report_import_batches(batch_id);
ALTER TABLE monthly_staff_counts ADD COLUMN IF NOT EXISTS import_batch_id BIGINT REFERENCES report_import_batches(batch_id);
CREATE INDEX IF NOT EXISTS monthly_collection_reports_city_month_idx ON monthly_collection_reports(city_id,report_month);
CREATE INDEX IF NOT EXISTS monthly_expense_reports_city_month_idx ON monthly_expense_reports(city_id,report_month);
CREATE INDEX IF NOT EXISTS monthly_staff_counts_city_month_idx ON monthly_staff_counts(city_id,report_month);
