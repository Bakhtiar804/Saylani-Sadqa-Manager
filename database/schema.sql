  rider_id VARCHAR(16) NOT NULL REFERENCES riders(rider_id),
  collector_team_id VARCHAR(40),
  task_id VARCHAR(20) NOT NULL REFERENCES rider_tasks(task_id),
  box_status_at_visit VARCHAR(32),
  seal_number_before VARCHAR(40),
  seal_number_after VARCHAR(40),
  seal_condition VARCHAR(32),
  box_condition VARCHAR(40),
  cash_notes_pkr NUMERIC(14, 2),
  cash_coins_pkr NUMERIC(14, 2),
  other_cash_pkr NUMERIC(14, 2),
  total_cash_counted_pkr NUMERIC(14, 2),
  counted_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  witness_name VARCHAR(120),
  collection_status VARCHAR(32),
  cash_handover_status VARCHAR(40),
  handover_reference VARCHAR(120),
  deposit_status VARCHAR(40),
  deposit_date DATE,
  deposit_reference VARCHAR(120),
  deposit_amount_pkr NUMERIC(14, 2),
  discrepancy_amount_pkr NUMERIC(14, 2),
  discrepancy_reason TEXT,
  verification_method VARCHAR(60),
  verified_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  donation_purpose_designation VARCHAR(120),
  remarks TEXT,
  created_at TIMESTAMPTZ,
  is_demo_record BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS field_collection_logs_task_idx ON field_collection_logs (task_id);
CREATE INDEX IF NOT EXISTS field_collection_logs_city_date_idx ON field_collection_logs (city_id, collection_date);

CREATE TABLE IF NOT EXISTS cash_handover_deposits (
  handover_id VARCHAR(20) PRIMARY KEY,
  handover_date DATE NOT NULL,
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  from_rider_id VARCHAR(16) NOT NULL REFERENCES riders(rider_id),
  received_by_team_id VARCHAR(40) NOT NULL REFERENCES team_members(team_id),
  collection_batch_reference VARCHAR(80) NOT NULL,
  amount_declared_pkr NUMERIC(14, 2) NOT NULL,
  amount_received_pkr NUMERIC(14, 2) NOT NULL,
  difference_pkr NUMERIC(14, 2) NOT NULL,
  handover_status VARCHAR(40) NOT NULL,
  deposit_status VARCHAR(40) NOT NULL,
  deposit_date DATE,
  deposit_reference VARCHAR(120),
  receipt_or_slip_reference VARCHAR(120),
  reconciled_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  reconciliation_notes TEXT,
  is_demo_record BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS cash_handover_city_date_idx ON cash_handover_deposits (city_id, handover_date);

