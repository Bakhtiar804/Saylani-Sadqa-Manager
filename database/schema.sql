DO $$ BEGIN
  ALTER TABLE team_members ADD CONSTRAINT team_members_account_status_check
    CHECK (account_status IN ('active', 'inactive', 'suspended'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  ALTER TABLE team_members ADD CONSTRAINT team_members_identity_auth_check
    CHECK (
      (identity_type = 'login_account' AND role_id IS NOT NULL AND password_hash IS NOT NULL)
      OR
      (identity_type IN ('field_staff', 'partner_identity') AND role_id IS NULL AND password_hash IS NULL)
    );
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS team_members_email_lower_unique
  ON team_members (LOWER(email));
CREATE UNIQUE INDEX IF NOT EXISTS team_members_team_id_unique ON team_members (team_id);
CREATE INDEX IF NOT EXISTS team_members_city_id_idx ON team_members (city_id);
CREATE INDEX IF NOT EXISTS team_members_role_id_idx ON team_members (role_id);

CREATE SEQUENCE IF NOT EXISTS branch_id_seq;
CREATE TABLE IF NOT EXISTS branches (
  branch_id VARCHAR(16) PRIMARY KEY DEFAULT ('BRN-' || TO_CHAR(nextval('branch_id_seq'), 'FM000')),
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  branch_name VARCHAR(120) NOT NULL,
  branch_code VARCHAR(40),
  address TEXT,
  contact_phone VARCHAR(32),
  status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (city_id, branch_name),
  UNIQUE (branch_id, city_id)
);
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS branch_id VARCHAR(16);
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS assigned_branch VARCHAR(120);
DO $$ BEGIN
  ALTER TABLE team_members ADD CONSTRAINT team_members_branch_id_fkey
    FOREIGN KEY (branch_id) REFERENCES branches(branch_id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
CREATE TABLE IF NOT EXISTS team_member_branch_assignments (
  team_id VARCHAR(40) PRIMARY KEY REFERENCES team_members(team_id),
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  branch_id VARCHAR(16) NOT NULL,
  assigned_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (branch_id, city_id) REFERENCES branches(branch_id, city_id)
);
CREATE INDEX IF NOT EXISTS team_member_branch_assignments_branch_idx ON team_member_branch_assignments (branch_id, team_id);

CREATE TABLE IF NOT EXISTS partners (
  partner_id VARCHAR(16) PRIMARY KEY,
  partner_name VARCHAR(160) NOT NULL,
  partner_type VARCHAR(80) NOT NULL,
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  contact_person VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  partnership_status VARCHAR(40) NOT NULL,
  agreement_start DATE,
  notes TEXT
);

CREATE SEQUENCE IF NOT EXISTS rider_id_seq;
CREATE TABLE IF NOT EXISTS riders (
  rider_id VARCHAR(16) PRIMARY KEY DEFAULT ('RID-' || TO_CHAR(nextval('rider_id_seq'), 'FM000000')),
  team_id VARCHAR(40) NOT NULL UNIQUE REFERENCES team_members(team_id),
  employment_status VARCHAR(24) NOT NULL,
  assigned_zone VARCHAR(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS donation_boxes (
  box_id VARCHAR(16) PRIMARY KEY,
  qr_code VARCHAR(40) NOT NULL UNIQUE,
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  area VARCHAR(100) NOT NULL,
  district VARCHAR(100),
  location_type VARCHAR(40) NOT NULL,
  location_description TEXT NOT NULL,
  custodian_team_id VARCHAR(40) REFERENCES team_members(team_id),
  partner_id VARCHAR(16) REFERENCES partners(partner_id),
  assigned_rider_id VARCHAR(16) REFERENCES riders(rider_id),
  installation_date DATE NOT NULL,
  box_status VARCHAR(32) NOT NULL,
  last_verified_date DATE,
  security_level VARCHAR(32) NOT NULL,
  is_demo_record BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS donation_boxes_city_id_idx ON donation_boxes (city_id);
CREATE INDEX IF NOT EXISTS donation_boxes_assigned_rider_idx ON donation_boxes (assigned_rider_id);
CREATE TABLE IF NOT EXISTS branch_box_assignments (
  box_id VARCHAR(16) PRIMARY KEY REFERENCES donation_boxes(box_id),
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  branch_id VARCHAR(16) NOT NULL,
  assigned_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (branch_id, city_id) REFERENCES branches(branch_id, city_id)
);
CREATE INDEX IF NOT EXISTS branch_box_assignments_branch_idx ON branch_box_assignments (branch_id, box_id);

CREATE TABLE IF NOT EXISTS collections (
  collection_id VARCHAR(20) PRIMARY KEY,
  box_id VARCHAR(16) NOT NULL REFERENCES donation_boxes(box_id),
  rider_id VARCHAR(16) NOT NULL REFERENCES riders(rider_id),
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  partner_id VARCHAR(16) REFERENCES partners(partner_id),
  collection_date DATE NOT NULL,
  collection_time TIME,
  collection_amount_pkr NUMERIC(14, 2) NOT NULL,
  collection_status VARCHAR(32) NOT NULL,
  recorded_by_team_id VARCHAR(40) NOT NULL REFERENCES team_members(team_id),
  verification_reference VARCHAR(120),
  notes TEXT,
  is_demo_record BOOLEAN NOT NULL DEFAULT FALSE,
  location_type VARCHAR(40),
  location_description TEXT,
  custodian_team_id VARCHAR(40) REFERENCES team_members(team_id),
  collector_team_id VARCHAR(40),
  seal_number_before VARCHAR(40),
  seal_number_after VARCHAR(40),
  seal_condition VARCHAR(32),
  box_condition VARCHAR(40),
  counted_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  witness_name VARCHAR(120),
  cash_notes_pkr NUMERIC(14, 2),
  cash_coins_pkr NUMERIC(14, 2),
  other_cash_pkr NUMERIC(14, 2),
  cash_total_counted_pkr NUMERIC(14, 2),
  cash_handover_status VARCHAR(40),
  handover_reference VARCHAR(120),
  deposit_status VARCHAR(40),
  deposit_date DATE,
  deposit_reference VARCHAR(120),
  deposit_amount_pkr NUMERIC(14, 2),
  discrepancy_amount_pkr NUMERIC(14, 2),
  discrepancy_reason TEXT,
  verification_method VARCHAR(60),
  verified_by_team_id VARCHAR(40) REFERENCES team_members(team_id),
  verified_at TIMESTAMPTZ,
  donation_purpose_designation VARCHAR(120),
  supporting_document_reference VARCHAR(160)
);
CREATE INDEX IF NOT EXISTS collections_date_idx ON collections (collection_date);
CREATE INDEX IF NOT EXISTS collections_city_date_idx ON collections (city_id, collection_date);
CREATE INDEX IF NOT EXISTS collections_box_date_idx ON collections (box_id, collection_date);
CREATE INDEX IF NOT EXISTS collections_status_idx ON collections (collection_status);

CREATE SEQUENCE IF NOT EXISTS rider_task_id_seq;
CREATE TABLE IF NOT EXISTS rider_tasks (
  task_id VARCHAR(20) PRIMARY KEY DEFAULT ('TSK-' || TO_CHAR(nextval('rider_task_id_seq'), 'FM000')),
  rider_id VARCHAR(16) NOT NULL REFERENCES riders(rider_id),
  box_id VARCHAR(16) NOT NULL REFERENCES donation_boxes(box_id),
  task_date DATE NOT NULL,
  task_type VARCHAR(60) NOT NULL,
  task_status VARCHAR(32) NOT NULL,
  completion_time TIME,
  completed_at TIMESTAMPTZ,
  notes TEXT,
  workflow_stage VARCHAR(32) NOT NULL DEFAULT 'assigned',
  workflow_events JSONB NOT NULL DEFAULT '[]'::jsonb,
  notification_read_at TIMESTAMPTZ,
  notification_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS rider_tasks_rider_date_idx ON rider_tasks (rider_id, task_date);

CREATE TABLE IF NOT EXISTS field_collection_logs (
  field_collection_id VARCHAR(20) PRIMARY KEY,
  collection_date DATE NOT NULL,
  collection_time TIME,
  box_id VARCHAR(16) NOT NULL REFERENCES donation_boxes(box_id),
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  area VARCHAR(100),
  location_type VARCHAR(40),
  full_location_description TEXT,
  partner_id VARCHAR(16) REFERENCES partners(partner_id),
