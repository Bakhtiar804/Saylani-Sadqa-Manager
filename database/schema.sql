ALTER TABLE team_members ADD COLUMN IF NOT EXISTS city_id VARCHAR(16) REFERENCES cities(city_id);
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS role_id SMALLINT REFERENCES roles(role_id);
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS identity_type VARCHAR(24);
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS account_status VARCHAR(16) NOT NULL DEFAULT 'active';
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS password_hash VARCHAR(128);
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE team_members ALTER COLUMN full_name SET NOT NULL;
ALTER TABLE team_members ALTER COLUMN team_id SET NOT NULL;
ALTER TABLE team_members ALTER COLUMN email SET NOT NULL;
ALTER TABLE team_members ALTER COLUMN identity_type SET NOT NULL;

