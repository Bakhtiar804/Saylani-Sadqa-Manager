BEGIN;

CREATE TABLE IF NOT EXISTS cities (
  city_id VARCHAR(16) PRIMARY KEY,
  city_name VARCHAR(100) NOT NULL UNIQUE,
  province VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS roles (
  role_id SMALLINT PRIMARY KEY,
  role_key VARCHAR(40) NOT NULL UNIQUE,
  display_name VARCHAR(80) NOT NULL UNIQUE
);

CREATE SEQUENCE IF NOT EXISTS team_member_id_seq;
CREATE TABLE IF NOT EXISTS team_members (
  team_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id VARCHAR(40) NOT NULL UNIQUE DEFAULT ('TEM-' || TO_CHAR(nextval('team_member_id_seq'), 'FM000000')),
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  phone VARCHAR(32),
  city_id VARCHAR(16) REFERENCES cities(city_id),
  role_id SMALLINT REFERENCES roles(role_id),
  identity_type VARCHAR(24) NOT NULL
    CHECK (identity_type IN ('login_account', 'field_staff', 'partner_identity')),
  account_status VARCHAR(16) NOT NULL DEFAULT 'active'
    CHECK (account_status IN ('active', 'inactive', 'suspended')),
  password_hash VARCHAR(128),
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT team_members_identity_auth_check CHECK (
    (identity_type = 'login_account' AND role_id IS NOT NULL AND password_hash IS NOT NULL)
    OR
    (identity_type IN ('field_staff', 'partner_identity') AND role_id IS NULL AND password_hash IS NULL)
  )
);

