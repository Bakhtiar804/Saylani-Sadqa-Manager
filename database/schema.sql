CREATE TABLE IF NOT EXISTS box_status_history (
  history_id VARCHAR(20) PRIMARY KEY,
  box_id VARCHAR(16) NOT NULL REFERENCES donation_boxes(box_id),
  previous_status VARCHAR(32) NOT NULL,
  new_status VARCHAR(32) NOT NULL,
  changed_on DATE NOT NULL,
  changed_by_team_id VARCHAR(40) NOT NULL REFERENCES team_members(team_id),
  reason TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS box_status_history_box_changed_idx ON box_status_history (box_id, changed_on);

CREATE TABLE IF NOT EXISTS security_incidents (
  incident_id VARCHAR(20) PRIMARY KEY,
  box_id VARCHAR(16) NOT NULL REFERENCES donation_boxes(box_id),
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  reported_by_team_id VARCHAR(40) NOT NULL REFERENCES team_members(team_id),
  incident_date DATE NOT NULL,
  incident_type VARCHAR(80) NOT NULL,
  severity VARCHAR(24) NOT NULL,
  incident_status VARCHAR(32) NOT NULL,
  resolution_notes TEXT
);
CREATE INDEX IF NOT EXISTS security_incidents_city_date_idx ON security_incidents (city_id, incident_date);

CREATE TABLE IF NOT EXISTS operational_costs (
  cost_record_id VARCHAR(20) PRIMARY KEY,
  city_id VARCHAR(16) NOT NULL REFERENCES cities(city_id),
  month CHAR(7) NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  cost_category VARCHAR(80) NOT NULL,
  cost_amount_pkr NUMERIC(14, 2) NOT NULL,
  notes TEXT
);
CREATE INDEX IF NOT EXISTS operational_costs_city_month_idx ON operational_costs (city_id, month);

CREATE TABLE IF NOT EXISTS activity_audit_log (
  audit_id CHAR(32) PRIMARY KEY,
  entity_type VARCHAR(40) NOT NULL,
  entity_id VARCHAR(40) NOT NULL,
  action VARCHAR(40) NOT NULL,
  actor_team_id VARCHAR(40) NOT NULL REFERENCES team_members(team_id),
  before_data JSONB,
  after_data JSONB,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS activity_audit_entity_idx
  ON activity_audit_log (entity_type, entity_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS activity_audit_actor_idx
  ON activity_audit_log (actor_team_id, occurred_at DESC);

