import "server-only";

import { getDatabasePool } from "@/lib/db";
import type { QueryResultRow } from "pg";

export type AdminAccount = {
  id: string;
  name: string;
  email: string;
  role: "Super Admin" | "Admin";
  createdAt: string | null;
  source: "environment" | "database";
};

type DatabaseAdmin = QueryResultRow & {
  id: string;
  full_name: string;
  email: string;
  password_hash: string;
  created_at: Date;
};

let schemaInitialization: Promise<void> | undefined;

async function ensureAdminAccountsTable(): Promise<void> {
  if (!schemaInitialization) {
    schemaInitialization = (async () => {
      const pool = getDatabasePool();
      await pool.query(`
        CREATE TABLE IF NOT EXISTS app_admins (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          full_name VARCHAR(120) NOT NULL,
          email VARCHAR(254) NOT NULL,
          password_hash VARCHAR(128) NOT NULL,
          created_by VARCHAR(254) NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
      `);
      await pool.query(`
        CREATE UNIQUE INDEX IF NOT EXISTS app_admins_email_lower_unique
        ON app_admins (LOWER(email))
      `);
    })().catch((error: unknown) => {
      schemaInitialization = undefined;
      throw error;
    });
  }

  await schemaInitialization;
}

export async function listAdminAccounts(
  superAdminEmail: string,
): Promise<AdminAccount[]> {
  await ensureAdminAccountsTable();
  const result = await getDatabasePool().query<DatabaseAdmin>(
    `SELECT id, full_name, email, created_at
     FROM app_admins
     ORDER BY created_at DESC, id DESC`,
  );

  return [
    {
      id: "super-admin",
      name: "Super Admin",
      email: superAdminEmail,
      role: "Super Admin",
      createdAt: null,
      source: "environment",
    },
    ...result.rows.map((admin) => ({
      id: admin.id,
      name: admin.full_name,
      email: admin.email,
      role: "Admin" as const,
      createdAt: admin.created_at.toISOString(),
      source: "database" as const,
    })),
  ];
}

export async function findAdminByEmail(email: string): Promise<{
  id: number;
  email: string;
  passwordHash: string;
} | null> {
  await ensureAdminAccountsTable();
  const result = await getDatabasePool().query<DatabaseAdmin>(
    `SELECT id, email, password_hash
     FROM app_admins
     WHERE LOWER(email) = $1
     LIMIT 1`,
    [email.toLowerCase()],
  );
  const admin = result.rows[0];
  if (!admin) return null;

  return {
    id: Number(admin.id),
    email: admin.email,
    passwordHash: admin.password_hash,
  };
}

export async function createAdminAccount(input: {
  name: string;
  email: string;
  passwordHash: string;
  createdBy: string;
}): Promise<AdminAccount> {
  await ensureAdminAccountsTable();
  const result = await getDatabasePool().query<DatabaseAdmin>(
    `INSERT INTO app_admins (full_name, email, password_hash, created_by)
     VALUES ($1, $2, $3, $4)
     RETURNING id, full_name, email, created_at`,
    [
      input.name,
      input.email.toLowerCase(),
      input.passwordHash,
      input.createdBy.toLowerCase(),
    ],
  );
  const admin = result.rows[0];

  return {
    id: admin.id,
    name: admin.full_name,
    email: admin.email,
    role: "Admin",
    createdAt: admin.created_at.toISOString(),
    source: "database",
  };
}
